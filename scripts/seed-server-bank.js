// Seed the server-bank pilot: read the REAL math-ntuc bank from
// public/index.html (TOPICS + FRESH_BANK) and write
// supabase/pilot-seed.sql — one INSERT per question, deduped by
// normalised stem. Run: node scripts/seed-server-bank.js
// The seed file is generated, not hand-written: do not hand-edit it,
// re-run this script. INSERTs are idempotent (on conflict do
// nothing), so the file is safe to run twice in the dashboard.
//
// The 44 stems are the SAME extraction the live-gen tests use
// (tests/live-gen.test.js BANK_STEMS): P3 quest (5) + P3 fresh from
// FRESH_BANK (10) + P3 warm (8) + P3 retry (6) + P4 quest (5) +
// P4 fresh (10). P4 warm/retry are NOT seeded: the pilot serves
// quest sets only, and warm-up stays bank. IDs are stable
// (math-ntuc-p3-0001.., math-ntuc-p4-0001..) so a re-run never
// renames a question an explorer has already mastered.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const PAGE_PATH = process.env.SB_PAGE_PATH || path.join(__dirname, '..', 'public', 'index.html');
const OUT_PATH = process.env.SB_OUT_PATH || path.join(__dirname, '..', 'supabase', 'pilot-seed.sql');
// live-gen lives next to the page (project lib/), resolved from the
// page path so the script works from its staging dir too.
const { liveGenNormStem } = require(path.join(path.dirname(PAGE_PATH), '..', 'lib', 'live-gen'));

function Q(q, o, a, c, j) { return { q, o, a, c, j }; }
function extractVar(src, name) {
  const s = src.indexOf('var ' + name + '=');
  let i = src.indexOf('=', s) + 1, depth = 0, inStr = false, strCh = '', esc = false;
  const start = i;
  for (; i < src.length; i++) {
    const ch = src[i];
    if (inStr) { if (esc) esc = false; else if (ch === '\\') esc = true; else if (ch === strCh) inStr = false; continue; }
    if (ch === '"' || ch === "'") { inStr = true; strCh = ch; continue; }
    if (ch === '[' || ch === '{') depth++;
    if (ch === ']' || ch === '}') { depth--; if (depth === 0) return src.slice(start, i + 1); }
  }
  throw new Error('no end ' + name);
}
function sqlStr(s) { return "'" + String(s == null ? '' : s).replace(/'/g, "''") + "'"; }

function main() {
  const html = fs.readFileSync(PAGE_PATH, 'utf8');
  const TOPICS = eval('(' + extractVar(html, 'TOPICS') + ')'); // eslint-disable-line no-eval
  const FRESH = eval('(' + extractVar(html, 'FRESH_BANK') + ')'); // eslint-disable-line no-eval
  const NTUC = TOPICS.find((t) => t.id === 'math-ntuc');
  if (!NTUC) throw new Error('math-ntuc not found in TOPICS');

  const groups = [
    { level: 3, kind: 'quest', rows: NTUC.quest || [] },
    { level: 3, kind: 'fresh', rows: FRESH['math-ntuc'] || [] },
    { level: 3, kind: 'warm', rows: NTUC.warm || [] },
    { level: 3, kind: 'retry', rows: NTUC.retry || [] },
    { level: 4, kind: 'quest', rows: NTUC.p4quest || [] },
    { level: 4, kind: 'fresh', rows: NTUC.p4fresh || [] },
  ];
  const seen = new Set();
  const out = [];
  let skipped = 0;
  const perLevel = { 3: 0, 4: 0 }; // ids are unique per level, across kinds
  groups.forEach((g) => {
    let n = 0;
    g.rows.forEach((q) => {
      const norm = liveGenNormStem(q.q);
      if (seen.has(norm)) { skipped++; return; }
      seen.add(norm);
      n++;
      perLevel[g.level]++;
      const id = 'math-ntuc-p' + g.level + '-' + String(perLevel[g.level]).padStart(4, '0');
      out.push(
        'insert into public.sb_questions (id, topic, level, sub_topic, stem, options, answer, explanation, joke, source) values ('
        + [sqlStr(id), sqlStr('math-ntuc'), g.level, sqlStr(g.kind), sqlStr(q.q), sqlStr(JSON.stringify(q.o)), q.a, sqlStr(q.c || ''), sqlStr(q.j || ''), sqlStr('bank')].join(', ')
        + ') on conflict (id) do nothing;'
      );
    });
    console.log('p' + g.level + ' ' + g.kind + ': ' + n + ' questions');
  });

  const header = [
    '-- Server-bank pilot seed — GENERATED by scripts/seed-server-bank.js, do not hand-edit.',
    '-- ' + out.length + ' questions (the real math-ntuc bank: P3 quest/fresh/warm/retry + P4 quest/fresh).',
    '-- Run AFTER supabase/pilot-schema.sql, in Supabase Dashboard -> SQL Editor.',
    '-- Idempotent: re-running it inserts nothing new (on conflict do nothing).',
    '',
  ].join('\n');
  fs.writeFileSync(OUT_PATH, header + out.join('\n') + '\n');
  console.log('wrote ' + OUT_PATH + ': ' + out.length + ' inserts' + (skipped ? ' (' + skipped + ' duplicate stems skipped)' : ''));
}

if (require.main === module) main();
module.exports = { main };
