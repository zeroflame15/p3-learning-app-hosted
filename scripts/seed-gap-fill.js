// Seed the gap-fill questions into the server bank: read the 6
// gap-fill JSON files and write supabase/gap-fill-seed.sql — one
// INSERT per question. Run: node scripts/seed-gap-fill.js
// The seed file is generated, not hand-written: do not hand-edit it,
// re-run this script. INSERTs are idempotent (on conflict do
// nothing), so the file is safe to run twice in the dashboard.
//
// IDs are '<topic>-p3-####' / '<topic>-p4-####' in file order, one
// counter per topic per level across the four banks (quest, fresh,
// warm, retry) — the same convention as the pilot seed
// (scripts/seed-server-bank.js). EXCEPTION: math-ntuc — the pilot
// seed already uses math-ntuc-p3-0001..0029 and
// math-ntuc-p4-0001..0015, so the gap-fill math-ntuc rows continue
// at p3-0030 and p4-0016; without this, 'on conflict do nothing'
// would silently skip them.
//
// Run AFTER supabase/pilot-schema.sql, in Supabase Dashboard ->
// SQL Editor. Do NOT re-seed the 44 pilot math-ntuc rows: they are
// the ORIGINAL bank questions, not in the gap-fill JSONs.
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const FILES = [
  'gap-fill/maths-new.json',
  'gap-fill/maths-topups.json',
  'gap-fill/english.json',
  'gap-fill/science.json',
  'gap-fill/chinese-a.json',
  'gap-fill/chinese-b.json',
];
const OUT_PATH = path.join(__dirname, '..', 'supabase', 'gap-fill-seed.sql');
// Pilot rows already in sb_questions, per topic per level.
const ALREADY_USED = { 'math-ntuc': { 3: 29, 4: 15 } };
// Bank order within a level, matching the assembly order.
const BANK_ORDER = ['quest', 'fresh', 'warm', 'retry'];
const TOPIC_SUB = {
  'eng-story': 'eng', 'eng-tense': 'eng', 'eng-story2': 'eng', 'eng-punct': 'eng',
  'eng-spelling': 'eng', 'eng-visual': 'eng',
  'math-mrt': 'math', 'math-hawker': 'math', 'math-ntuc': 'math', 'math-frac': 'math',
  'math-length': 'math', 'math-time': 'math', 'math-area': 'math', 'math-angles': 'math', 'math-bargraphs': 'math',
  'sci-frog': 'sci', 'sci-magnet': 'sci', 'sci-plants': 'sci',
  'sci-classification': 'sci', 'sci-materials': 'sci',
  'chi-listen': 'chi', 'chi-family': 'chi', 'chi-school': 'chi',
  'chi-char': 'chi', 'chi-picword': 'chi', 'chi-collocation': 'chi', 'chi-sequencing': 'chi',
  'chi-sentence': 'chi', 'chi-reading': 'chi', 'chi-composition': 'chi', 'chi-oral': 'chi',
};

function sqlStr(s) { return "'" + String(s == null ? '' : s).replace(/'/g, "''") + "'"; }
function normStem(s) {
  return String(s || '').toLowerCase().replace(/[^a-z0-9\u4e00-\u9fff]+/g, ' ').trim().replace(/\s+/g, ' ');
}

function main() {
  const counters = {}; // topic -> {3: n, 4: n} (already-used counts)
  const seen = new Set();
  const out = [];
  const perFile = {};
  const perSubject = { eng: 0, math: 0, sci: 0, chi: 0 };
  const perTopic = {};
  let skipped = 0;

  function nextId(topic, level) {
    if (!counters[topic]) {
      const used = ALREADY_USED[topic] || { 3: 0, 4: 0 };
      counters[topic] = { 3: used[3], 4: used[4] };
    }
    counters[topic][level]++;
    return topic + '-p' + level + '-' + String(counters[topic][level]).padStart(4, '0');
  }
  function emit(topic, kind, level, q) {
    const norm = normStem(q.q);
    if (seen.has(norm)) { skipped++; console.log('  SKIP duplicate stem: ' + topic + ' ' + kind + ' L' + level + ': ' + q.q.slice(0, 60)); return; }
    seen.add(norm);
    const id = nextId(topic, level);
    out.push(
      'insert into public.sb_questions (id, topic, level, sub_topic, stem, options, answer, explanation, joke, source) values ('
      + [sqlStr(id), sqlStr(topic), level, sqlStr(kind), sqlStr(q.q), sqlStr(JSON.stringify(q.o)), q.a, sqlStr(q.c || ''), sqlStr(q.j || ''), sqlStr('bank')].join(', ')
      + ') on conflict (id) do nothing;'
    );
    perSubject[TOPIC_SUB[topic]]++;
    perTopic[topic] = (perTopic[topic] || 0) + 1;
  }

  for (const f of FILES) {
    const data = JSON.parse(fs.readFileSync(path.join(__dirname, '..', f), 'utf8'));
    let n = 0;
    const before = out.length;
    for (const t of (data.newTopics || [])) {
      for (const level of [3, 4]) {
        for (const kind of BANK_ORDER) {
          const key = level === 3 ? kind : 'p4' + kind;
          for (const q of (t[key] || [])) { emit(t.id, kind, level, q); n++; }
        }
      }
    }
    for (const u of (data.topUps || [])) {
      for (const q of (u.questions || [])) { emit(u.topicId, u.kind, u.level, q); n++; }
    }
    perFile[f] = out.length - before;
    console.log(f + ': ' + perFile[f] + ' questions');
  }

  if (out.length !== 1536) throw new Error('expected 1,536 gap-fill questions, got ' + out.length);
  const header = [
    '-- Gap-fill seed — GENERATED by scripts/seed-gap-fill.js, do not hand-edit.',
    '-- ' + out.length + ' questions (the 2026-11-08 question gap-fill: 17 new topics + top-ups for the 14 original topics).',
    '-- Per subject: English ' + perSubject.eng + ', Maths ' + perSubject.math + ', Science ' + perSubject.sci + ', Chinese ' + perSubject.chi + '.',
    '-- Run AFTER supabase/pilot-schema.sql, in Supabase Dashboard -> SQL Editor.',
    '-- Idempotent: re-running it inserts nothing new (on conflict do nothing).',
    '-- math-ntuc ids continue after the pilot seed (p3-0030+, p4-0016+).',
    '',
  ].join('\n');
  fs.writeFileSync(OUT_PATH, header + out.join('\n') + '\n');
  console.log('wrote ' + OUT_PATH + ': ' + out.length + ' inserts' + (skipped ? ' (' + skipped + ' duplicate stems skipped)' : ''));
  console.log('per subject:', JSON.stringify(perSubject));
  console.log('per topic:', JSON.stringify(perTopic));
}

if (require.main === module) main();
module.exports = { main };
